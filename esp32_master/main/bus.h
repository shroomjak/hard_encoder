#ifndef BUS_H
#define BUS_H
/*
 * Общая шина Modbus RTU (UART2, RS485, 8E1) для обоих режимов прошивки ESP32.
 * Один master на линии: рабочий режим и калибровка используют одни и те же
 * функции обмена, поэтому разницы в кадрировании и таймаутах между ними нет.
 */
#include <stdint.h>
#include "esp_err.h"

/* Полная карта входных регистров снимка головки: адреса 0…10. */
#define REG_COUNT 11

/* Создать master, назначить пины, запустить стек. Вызывать один раз из app_main(). */
esp_err_t bus_init(void);

/* Стандартный запрос Modbus. first — адрес регистра на проводе с нуля;
 * count — число 16-битных регистров. Для FC06 *words — записываемое значение,
 * для FC04 буфер заполняется в порядке uint16_t. Фрейм и CRC здесь не строятся.
 * После каждого запроса выдерживается пауза 20 мс на шине. */
esp_err_t bus_request(uint8_t id, uint8_t function, uint16_t first,
                      uint16_t count, uint16_t *words);

#endif /* BUS_H */
